#!/usr/bin/env python3
"""Generate Secp256k1/Certificates.lean: Pratt primality certificates for the
secp256k1 field prime p and group order n.

For every prime q in the certificate tree (other than 2) this finds a witness
a and the factorisation of q - 1, and emits a Lean theorem checked by the
Lucas test in Secp256k1/Primality.lean (`decide +kernel`). The script is only
needed to regenerate the file; Lean checks every certificate independently.

Usage:
    pip install sympy
    python3 scripts/gen_pratt_certificates.py > Secp256k1/Certificates.lean
"""

from sympy import factorint, isprime

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141

certs = {}


def certify(q: int) -> None:
    if q == 2 or q in certs:
        return
    assert isprime(q)
    factors = sorted(factorint(q - 1).items())
    for a in range(2, 1000):
        if pow(a, q - 1, q) == 1 and all(pow(a, (q - 1) // r, q) != 1 for r, _ in factors):
            break
    else:
        raise ValueError(f"no Lucas witness for {q}")
    certs[q] = (a, factors)
    for r, _ in factors:
        certify(r)


def name(q: int) -> str:
    return "prime_two" if q == 2 else f"prime_{q}"


def lean_list(factors) -> str:
    return "[" + ", ".join(f"({r}, {e})" for r, e in factors) + "]"


def all_prime(factors) -> str:
    out = ".nil"
    for r, _ in reversed(factors):
        out = f"(.cons {name(r)} {out})"
    return out


def main() -> None:
    certify(P)
    certify(N)
    print("import Secp256k1.Primality")
    print()
    print("/-!")
    print("# Primality of `p` and `n`")
    print()
    print("Pratt certificates generated by `scripts/gen_pratt_certificates.py`; do not")
    print("edit by hand. Each prime `q` is certified by the Lucas test with a witness")
    print("`a` and the factorisation of `q - 1` into primes certified earlier in the")
    print("file. Every check is evaluated by the Lean kernel (`decide +kernel`).")
    print("-/")
    print()
    print("namespace Secp256k1.Certificates")
    print()
    print("open Secp256k1")
    print()
    for q in sorted(certs):
        a, factors = certs[q]
        if q in (P, N):
            continue
        print(f"theorem {name(q)} : IsPrime {q} :=")
        print(f"  (LucasCert.of_check (N := {q}) (a := {a}) (fs := {lean_list(factors)})")
        print(f"    (by decide +kernel) {all_prime(factors)}).isPrime")
        print()
    for label, value in (("p", P), ("n", N)):
        a, factors = certs[value]
        print(f"/-- The Lucas certificate for `{label}`. -/")
        print(f"theorem {label}_cert : LucasCert {label} {a} {lean_list(factors)} :=")
        print(f"  LucasCert.of_check (by decide +kernel) {all_prime(factors)}")
        print()
    print("end Secp256k1.Certificates")
    print()
    print("namespace Secp256k1")
    print()
    print("/-- The field prime `p` is prime. -/")
    print("theorem p_isPrime : IsPrime p := Certificates.p_cert.isPrime")
    print()
    print("/-- The group order `n` is prime. -/")
    print("theorem n_isPrime : IsPrime n := Certificates.n_cert.isPrime")
    print()
    print("/-- Fermat's little theorem modulo `p`. -/")
    print("theorem fermat_p (x : Nat) (h0 : 0 < x) (h : x < p) : x ^ (p - 1) % p = 1 :=")
    print("  Certificates.p_cert.fermat x h0 h")
    print()
    print("/-- Fermat's little theorem modulo `n`. -/")
    print("theorem fermat_n (x : Nat) (h0 : 0 < x) (h : x < n) : x ^ (n - 1) % n = 1 :=")
    print("  Certificates.n_cert.fermat x h0 h")
    print()
    print("end Secp256k1")


if __name__ == "__main__":
    main()
