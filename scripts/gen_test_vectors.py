#!/usr/bin/env python3
"""Generate Tests/Vectors.lean from independent reference implementations.

* libsecp256k1 (through the `coincurve` bindings) for key derivation,
  low-S RFC 6979 signatures, DER encoding and public key recovery;
* `python-ecdsa` for high-S (non-normalised) RFC 6979 signatures, digests
  longer than 256 bits, and RFC 6979 additional data;
* Bitcoin Core's low-R grinding loop (`CKey::Sign`), on top of libsecp256k1.

Usage:
    pip install coincurve ecdsa
    python3 scripts/gen_test_vectors.py > Tests/Vectors.lean

All inputs are fixed, so the output is reproducible.
"""

import hashlib
import hmac

import coincurve
from coincurve._libsecp256k1 import ffi, lib
from ecdsa import SECP256k1, SigningKey
from ecdsa.util import sigencode_strings

N = SECP256k1.order


def h(b: bytes) -> str:
    return b.hex()


def seeded_key(i: int) -> int:
    return int.from_bytes(hashlib.sha256(b"lean-ecdsa key %d" % i).digest(), "big") % N


PRIVS = [
    1,
    2,
    3,
    0xDEADBEEF,
    N - 1,
    N // 2,
    0xC9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721,
] + [seeded_key(i) for i in range(8)]

MESSAGES = [
    b"",
    b"abc",
    b"sample",
    b"test",
    b"Satoshi Nakamoto",
    b"Everything should be made as simple as possible, but not simpler.",
    bytes(range(256)) * 4,
]


def dsha256(b: bytes) -> bytes:
    return hashlib.sha256(hashlib.sha256(b).digest()).digest()


def lean_str(s: str) -> str:
    return '"' + s + '"'


def sign_extra(priv: int, msg: bytes, extra: bytes) -> bytes:
    """libsecp256k1 RFC 6979 nonce with 32 bytes of additional data."""
    sk = coincurve.PrivateKey.from_int(priv)
    ndata = ffi.new("unsigned char[32]", extra)
    return sk.sign_recoverable(msg, custom_nonce=(lib.secp256k1_nonce_function_rfc6979, ndata))


def bitcoin_core_sign(priv: int, hash32: bytes) -> tuple[int, bytes]:
    """Bitcoin Core's `CKey::Sign`: libsecp256k1 RFC 6979 signing, retried with
    `ndata = LE32(counter) || 0^28`, counter = 1, 2, ..., until r < 2^255.
    Returns the number of attempts and the DER signature."""
    sk = coincurve.PrivateKey.from_int(priv)
    der = sk.sign(hash32, hasher=None)
    attempts = 1
    while der[3] > 32:  # r needs 33 DER bytes iff r >= 2^255
        ndata = ffi.new("unsigned char[32]", attempts.to_bytes(4, "little") + bytes(28))
        der = sk.sign(
            hash32, hasher=None, custom_nonce=(lib.secp256k1_nonce_function_rfc6979, ndata)
        )
        attempts += 1
    return attempts, der


def main() -> None:
    out = []
    w = out.append
    w("/-! Generated by `scripts/gen_test_vectors.py`. Do not edit by hand. -/")
    w("")
    w("namespace Tests.Vectors")
    w("")

    # SHA-256 (hashlib), including every padding boundary around one and two blocks.
    w("/-- `(message, SHA-256(message))` from Python's `hashlib`. -/")
    w("def sha256 : List (String × String) := [")
    sha_msgs = [
        b"",
        b"abc",
        b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq",
        b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmn"
        b"hijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu",
        bytes(range(256)) * 5,
    ] + [bytes((i * 7 + 3) % 256 for i in range(k)) for k in (55, 56, 57, 63, 64, 65, 119, 120, 128)]
    rows = [f"  ({lean_str(h(m))}, {lean_str(hashlib.sha256(m).hexdigest())})" for m in sha_msgs]
    w(",\n".join(rows))
    w("]")
    w("")

    # HMAC-SHA-256: RFC 4231 test cases 1-4, 6, 7 (checked against Python's `hmac`).
    w("/-- `(key, data, HMAC-SHA-256)`: RFC 4231 test cases 1–4, 6, 7. -/")
    w("def hmacSha256 : List (String × String × String) := [")
    hmac_cases = [
        (b"\x0b" * 20, b"Hi There"),
        (b"Jefe", b"what do ya want for nothing?"),
        (b"\xaa" * 20, b"\xdd" * 50),
        (bytes(range(1, 26)), b"\xcd" * 50),
        (b"\xaa" * 131, b"Test Using Larger Than Block-Size Key - Hash Key First"),
        (
            b"\xaa" * 131,
            b"This is a test using a larger than block-size key and a larger than "
            b"block-size data. The key needs to be hashed before being used by the "
            b"HMAC algorithm.",
        ),
    ]
    rows = [
        f"  ({lean_str(h(k))}, {lean_str(h(m))}, {lean_str(hmac.new(k, m, hashlib.sha256).hexdigest())})"
        for k, m in hmac_cases
    ]
    w(",\n".join(rows))
    w("]")
    w("")

    # Scalar multiplication: k • G (uncompressed SEC 1).
    w("/-- `(k, SEC1-uncompressed(k • G))` from libsecp256k1. -/")
    w("def scalarMul : List (Nat × String) := [")
    ks = PRIVS + [7, 20, 112233445566778899, 2**128, 2**255 - 19]
    rows = []
    for k in ks:
        pub = coincurve.PublicKey.from_secret(k.to_bytes(32, "big")).format(compressed=False)
        rows.append(f"  (0x{k:x}, {lean_str(h(pub))})")
    w(",\n".join(rows))
    w("]")
    w("")

    # Low-S RFC 6979 signatures from libsecp256k1.
    w("/-- Signatures from libsecp256k1 (`secp256k1_ecdsa_sign_recoverable`, RFC 6979, low-S):")
    w("`(priv, msg, compressed pub, uncompressed pub, compact sig, DER sig, recId)`. -/")
    w("def libsecp256k1 : List (String × String × String × String × String × String × Nat) := [")
    rows = []
    for d in PRIVS:
        for msg in MESSAGES:
            sk = coincurve.PrivateKey.from_int(d)
            pub = sk.public_key
            rec = sk.sign_recoverable(msg)
            der = sk.sign(msg)
            assert coincurve.PublicKey.from_signature_and_message(rec, msg) == pub
            rows.append(
                "  ({}, {}, {}, {}, {}, {}, {})".format(
                    lean_str(d.to_bytes(32, "big").hex()),
                    lean_str(h(msg)),
                    lean_str(h(pub.format(compressed=True))),
                    lean_str(h(pub.format(compressed=False))),
                    lean_str(h(rec[:64])),
                    lean_str(h(der)),
                    rec[64],
                )
            )
    w(",\n".join(rows))
    w("]")
    w("")

    # Additional data (RFC 6979 §3.6) via libsecp256k1's ndata.
    w("/-- libsecp256k1 signatures with 32 bytes of RFC 6979 additional data:")
    w("`(priv, msg, extra, compact sig, recId)`. -/")
    w("def libsecp256k1Extra : List (String × String × String × String × Nat) := [")
    rows = []
    for i, d in enumerate(PRIVS[:6]):
        for msg in MESSAGES[:4]:
            extra = hashlib.sha256(b"extra %d" % i + msg).digest()
            rec = sign_extra(d, msg, extra)
            rows.append(
                "  ({}, {}, {}, {}, {})".format(
                    lean_str(d.to_bytes(32, "big").hex()),
                    lean_str(h(msg)),
                    lean_str(h(extra)),
                    lean_str(h(rec[:64])),
                    rec[64],
                )
            )
    w(",\n".join(rows))
    w("]")
    w("")

    # python-ecdsa: raw RFC 6979 signatures, no low-S normalisation, arbitrary digest sizes.
    w("/-- `python-ecdsa` `sign_digest_deterministic` (HMAC-SHA-256, no low-S normalisation):")
    w("`(priv, digest, extra, r, s)`. Digests of 20, 32 and 64 bytes exercise `bits2int`. -/")
    w("def pythonEcdsa : List (String × String × String × String × String) := [")
    rows = []
    for i, d in enumerate(PRIVS):
        sk = SigningKey.from_secret_exponent(d, curve=SECP256k1, hashfunc=hashlib.sha256)
        for j, msg in enumerate(MESSAGES[:5]):
            for digest in (
                hashlib.sha256(msg).digest(),
                hashlib.sha512(msg).digest(),
                hashlib.sha1(msg).digest(),
            ):
                extra = b"" if (i + j) % 2 == 0 else hashlib.sha256(b"e%d" % j).digest()[: 8 + j]
                r, s = sk.sign_digest_deterministic(
                    digest,
                    hashfunc=hashlib.sha256,
                    sigencode=sigencode_strings,
                    extra_entropy=extra,
                    allow_truncate=True,
                )
                rows.append(
                    "  ({}, {}, {}, {}, {})".format(
                        lean_str(d.to_bytes(32, "big").hex()),
                        lean_str(h(digest)),
                        lean_str(h(extra)),
                        lean_str(h(r)),
                        lean_str(h(s)),
                    )
                )
    w(",\n".join(rows))
    w("]")
    w("")
    # Bitcoin Core's low-R grinding on top of libsecp256k1.
    w("/-- Bitcoin Core `CKey::Sign` (low-R grinding over libsecp256k1):")
    w("`(priv, hash, attempts, DER sig)`. -/")
    w("def bitcoinCoreLowR : List (String × String × Nat × String) := [")
    rows = []
    cases = [(d, b"grind %d" % j) for d in PRIVS[:8] for j in range(4)]
    # Add cases that need at least four attempts.
    j = 0
    while sum(1 for d, m in cases if bitcoin_core_sign(d, dsha256(m))[0] >= 4) < 6:
        d = PRIVS[j % len(PRIVS)]
        if bitcoin_core_sign(d, dsha256(b"grind more %d" % j))[0] >= 4:
            cases.append((d, b"grind more %d" % j))
        j += 1
    for d, msg in cases:
        hash32 = dsha256(msg)
        attempts, der = bitcoin_core_sign(d, hash32)
        rows.append(
            "  ({}, {}, {}, {})".format(
                lean_str(d.to_bytes(32, "big").hex()),
                lean_str(h(hash32)),
                attempts,
                lean_str(h(der)),
            )
        )
    w(",\n".join(rows))
    w("]")
    w("")
    w("end Tests.Vectors")
    print("\n".join(out))


if __name__ == "__main__":
    main()
